import { createHash } from "node:crypto";
import {
  copyFile,
  mkdir,
  readFile,
  writeFile,
} from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { securityHeaders } from "../src/security/headers.ts";

const projectRoot = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
);
const sourcePath = resolve(
  projectRoot,
  "node_modules/maplibre-gl/dist/maplibre-gl-csp-worker.js",
);
const destinationPath = resolve(
  projectRoot,
  "public/vendor/maplibre-gl-csp-worker.js",
);
const headersPath = resolve(projectRoot, "public/_headers");

await mkdir(dirname(destinationPath), { recursive: true });
await copyFile(sourcePath, destinationPath);
await writeFile(
  headersPath,
  createCloudflareHeadersFile(),
  "utf8",
);

const worker = await readFile(destinationPath);
const digest = createHash("sha256")
  .update(worker)
  .digest("hex")
  .slice(0, 12);

console.log(
  `Synced MapLibre CSP worker (${worker.byteLength} bytes, sha256:${digest})`,
);
console.log("Generated Cloudflare static asset headers");

function createCloudflareHeadersFile() {
  const globalHeaders = securityHeaders
    .map(({ key, value }) => `  ${key}: ${value}`)
    .join("\n");

  return `# Generated by scripts/sync-static-assets.mjs.
/*
${globalHeaders}

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/vendor/*
  Cache-Control: public, max-age=0, must-revalidate

/maps/*
  Cache-Control: public, max-age=0, must-revalidate
  Accept-Ranges: bytes
`;
}
